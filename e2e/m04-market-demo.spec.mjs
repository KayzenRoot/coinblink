import { test, expect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
test("M04 market radar is offline, accessible and has no quotes", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  const outside = [];
  page.on("request", r => {
    if (!r.url().startsWith("http://127.0.0.1:4321/") && !r.url().startsWith("data:")) outside.push(r.url());
  });
  const response = await page.goto("/demo/markets");
  expect(response?.status()).toBe(200);
  await expect(page.getByRole("heading", { name: "Market & radar demonstration" })).toBeVisible();
  await expect(page.locator("[data-m04-entry]")).toHaveCount(3);
  await expect(page.getByRole("heading", { name: "Radar 24h" })).toBeVisible();
  await expect(page.getByText("UNAVAILABLE · NO LIVE DATA")).toBeVisible();
  const availability = page.getByRole("combobox", { name: "Illustration availability" });
  await availability.selectOption("STALE");
  await expect(page.locator("[data-m04-entry]:visible")).toHaveCount(1);
  await expect(page.locator("[data-m04-entry]:visible").first()).toContainText("BTC/USD");
  await page.locator("[data-m04-query]").fill("eth");
  await expect(page.locator("[data-m04-entry]:visible")).toHaveCount(0);
  await expect(page.locator("[data-m04-empty]")).toBeVisible();
  await availability.selectOption("UNAVAILABLE");
  await expect(page.locator("[data-m04-entry]:visible")).toHaveCount(1);
  await expect(page.locator("[data-m04-entry]:visible").first()).toContainText("ETH/USD");
  await page.locator("[data-m04-query]").fill("not-listed");
  await expect(page.locator("[data-m04-empty]")).toBeVisible();
  await page.locator("[data-m04-query]").fill("");
  await expect(page.locator("[data-m04-entry]:visible")).toHaveCount(2);
  await availability.selectOption("all");
  await expect(page.locator("[data-m04-entry]:visible")).toHaveCount(3);
  await expect(page.locator("[data-m04-empty]")).toBeHidden();
  await expect(page.locator("[data-m04-count]")).toHaveText("3 unavailable example assets");
  await expect(page.getByRole("heading", { name: "Offline market data readiness · DEMO" })).toBeVisible();
  await expect(page.locator(".m04-readiness")).toContainText("0 live feeds");
  await expect(page.locator(".m04-readiness")).toContainText("0 tradable assets");
  const report = page.locator("[data-m04-entry]").first().locator(".m04-readiness-detail");
  await report.locator("summary").click();
  await expect(report).toHaveAttribute("open", "");
  await expect(report).toContainText("RIGHTS_NOT_CLEARED");
  await expect(report).toContainText("NO_LIVE_FEED");
  await expect(report).toContainText("NO_CAPTURED_OBSERVATION");
  const compare = page.getByRole("button", { name: "Compare offline readiness" });
  await compare.click();
  await expect(page.locator("[data-m04-comparison]")).toContainText("Choose two different offline examples");
  await page.locator("[data-m04-first]").selectOption("BTC");
  await page.locator("[data-m04-second]").selectOption("BTC");
  await compare.click();
  await expect(page.locator("[data-m04-comparison]")).toContainText("No market data was fetched");
  await page.locator("[data-m04-second]").selectOption("ETH");
  await compare.click();
  await expect(page.locator("[data-m04-comparison]")).toContainText("BTC (STALE) and ETH (UNAVAILABLE)");
  await expect(page.locator("[data-m04-comparison]")).toContainText("BOTH NOT LIVE · NO QUOTES · NO TRADING");
  const gaps = page.locator("[data-m04-comparison-gaps]");
  await expect(gaps).toBeVisible();
  await expect(gaps).toContainText("Shared blockers: RIGHTS_NOT_CLEARED, NO_CAPTURED_OBSERVATION, NO_LIVE_FEED");
  await expect(gaps).toContainText("BTC only: OUTDATED_ILLUSTRATION");
  await expect(gaps).toContainText("ETH only: NO_ILLUSTRATION_TIMESTAMP");
  await expect(gaps).toContainText("no prices, permission or trading advice");
  await page.locator("[data-m04-second]").selectOption("BTC");
  await expect(gaps).toBeHidden();
  await compare.click();
  await expect(gaps).toBeHidden();
  await page.locator("[data-m04-second]").selectOption("ETH");
  await compare.click();
  await expect(gaps).toBeVisible();
  // CB-P0-FILTER-COMPARISON-VISIBILITY-001: hidden mock assets cannot be compared.
  await availability.selectOption("STALE");
  await expect(gaps).toBeHidden();
  await expect(gaps).toHaveText("");
  await compare.click();
  await expect(gaps).toBeHidden();
  await expect(page.locator("[data-m04-comparison]")).toContainText("visible under current filters");
  await availability.selectOption("all");
  await compare.click();
  await expect(gaps).toBeVisible();
  await page.locator("[data-m04-query]").fill("eth");
  await expect(gaps).toBeHidden();
  await compare.click();
  await expect(gaps).toBeHidden();
  await page.locator("[data-m04-query]").fill("");
  await compare.click();
  await expect(gaps).toBeVisible();
  for (const width of [390, 768, 1366]) {
    await page.setViewportSize({ width, height: 900 });
    const bounds = await page.locator(".m04-compare").boundingBox();
    expect(bounds).toBeTruthy();
    expect(bounds.x).toBeGreaterThanOrEqual(-1);
    expect(bounds.x + bounds.width).toBeLessThanOrEqual(width + 1);
  }

  await expect(page.locator('meta[name="robots"]')).toHaveAttribute("content", /noindex/);
  expect(outside).toEqual([]);
  const audit = await new AxeBuilder({ page }).withTags(["wcag2a","wcag2aa","wcag21a","wcag21aa"]).analyze();
  expect(audit.violations).toEqual([]);
});

test("M04 live adapter stays disabled and silent by default", async ({ page }) => {
  const external = [];
  const writes = [];
  page.on("request", (request) => {
    if (!request.url().startsWith("http://127.0.0.1:4321/") && !request.url().startsWith("data:")) external.push(request.url());
    if (!["GET", "HEAD"].includes(request.method())) writes.push(request.url());
  });
  const response = await page.goto("/demo/markets/live");
  expect(response?.status()).toBe(200);
  await expect(page.locator("h1")).toHaveCount(1);
  await expect(page.locator('meta[name="robots"]')).toHaveAttribute("content", /noindex/);
  await expect(page.getByRole("heading", { name: "LIVE FEED DISABLED" })).toBeVisible();
  await expect(page.getByText(/No request was made/u)).toBeVisible();
  await expect(page.getByText(/verified data licence/u)).toBeVisible();
  // No price table exists while the adapter is off.
  await expect(page.locator("table")).toHaveCount(0);
  expect(external).toEqual([]);
  expect(writes).toEqual([]);
  const axe = await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21a", "wcag21aa"]).analyze();
  expect(axe.violations).toEqual([]);
});
